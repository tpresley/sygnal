// Markdown report for one analyzed run.
import { PHASE_ORDER, mean } from './aggregate.mjs'
import { CATALOG_BY_ID } from '../catalog.mjs'
import { recommendationSet } from './recommend.mjs'

const f1 = (x) => (x == null ? '—' : (Math.round(x * 10) / 10).toString())
const f0 = (x) => (x == null ? '—' : Math.round(x).toString())
const k = (x) => (x == null ? '—' : `${(x / 1000).toFixed(1)}k`)
const pct = (x) => (x == null ? '—' : `${Math.round(x * 100)}%`)
const mm = (s) => (s ? `${f1(s.mean)} / ${f1(s.median)}` : '—')
const usd = (s) => (s?.mean != null ? `$${s.mean.toFixed(2)} / $${s.median.toFixed(2)}` : '—')
const cell = (c) => String(c ?? '').replace(/(?<!\\)\|/g, '\\|').replace(/\n/g, ' ')
const table = (head, rows) => [`| ${head.map(cell).join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n')
const taskLabel = (t) => t.replace(/^(\d\d)-/, '$1 ')

const PHASE_DOC = [
  ['orient', 'reading the starter and app files, `ls`/`find`/`cat` in the trial dir, other shell commands'],
  ['learn', 'Skill tool, reading skill files, reading `node_modules/<framework>` source, `.d.ts` or docs, web docs'],
  ['implement', 'Write/Edit (or shell writes) to non-test files'],
  ['test-authoring', "writing, reading or deleting the agent's own test files"],
  ['verify', 'build/test runs (lib/transcript.mjs `isRunCommand`), ad-hoc `node` checks, driving the app in the browser pane'],
  ['debug', 'everything after a failed build/test run until the next passing run (re-runs, reading errors, fixes), when the failure matches no known defect'],
  ['tooling-friction', 'the same span when the failure matches a known defect in the catalog, plus any command the environment refused (HARNESS-GUARD)'],
  ['think', 'assistant text with no tool call'],
  ['report', 'writing and delivering the final report (SubagentHandback and after)'],
  ['other', 'unclassified tools; reported as the unattributed share'],
]

export function renderMarkdown({ meta, agg, records, tracker, skill, docs = null }) {
  const out = []
  const P = (s = '') => out.push(s)
  const analyzed = records.filter((r) => r.phases)
  const sy = agg.overallShared.sygnal ?? agg.overall.sygnal
  const re = agg.overallShared.react ?? agg.overall.react

  P(`# Friction analysis — run \`${meta.run}\``)
  P()
  P(`Generated by \`analysis/analyze.mjs\` from ${meta.trialsAnalyzed} of ${meta.trialsInMap} mapped trials (${meta.trialsScored} scored). Transcripts: per-trial JSONL; final code: the trial dirs; skill: \`${meta.skillDir.replace(process.env.HOME ?? '', '~')}\`. sygnal-check: ${meta.sygnalCheck ? 'run' : 'skipped'}.${meta.methods?.length ? ` Trial method: ${meta.methods.join(', ')}.` : ''}${meta.models?.length ? ` Model: ${meta.models.join(', ')}.` : ''} Re-run the script as trials arrive; the output is regenerated from scratch.`)
  const flagged = records.filter((r) => r.flags?.length)
  if (flagged.length) P(`\nData gaps: ${flagged.map((r) => `${r.trial} (${r.flags.join(', ')})`).join('; ')}.`)
  P()

  // ---- headline
  P('## Headline')
  P()
  const shared = agg.sharedTasks
  P(`Shared tasks (both arms): ${shared.map(taskLabel).join(', ') || 'none'}. Means/medians below are over the trials of those tasks; per-task tables follow.`)
  P()
  const head = ['Metric', 'Sygnal', 'React', 'Ratio (mean)']
  const row = (label, key, fmt = mm, ratio = true) => [label, fmt(sy?.[key]), fmt(re?.[key]), ratio && sy?.[key]?.mean && re?.[key]?.mean ? `${(sy[key].mean / re[key].mean).toFixed(2)}×` : '—']
  P(
    table(head, [
      ['Trials (pass)', `${sy?.n ?? 0} (${sy?.pass ?? 0})`, `${re?.n ?? 0} (${re?.pass ?? 0})`, '—'],
      row('Wall s (mean / median)', 'wall'),
      [`Peak context tokens (mean / median)`, sy ? `${k(sy.peakContext.mean)} / ${k(sy.peakContext.median)}` : '—', re ? `${k(re.peakContext.mean)} / ${k(re.peakContext.median)}` : '—', sy && re ? `${(sy.peakContext.mean / re.peakContext.mean).toFixed(2)}×` : '—'],
      [`Cache-creation tokens (mean)`, k(sy?.cacheCreation.mean), k(re?.cacheCreation.mean), sy && re ? `${(sy.cacheCreation.mean / re.cacheCreation.mean).toFixed(2)}×` : '—'],
      ...(sy?.costUsd?.mean != null || re?.costUsd?.mean != null ? [[`Cost USD per trial (mean / median)`, usd(sy?.costUsd), usd(re?.costUsd), sy?.costUsd?.mean && re?.costUsd?.mean ? `${(sy.costUsd.mean / re.costUsd.mean).toFixed(2)}×` : '—'], [`Billed tokens per trial (mean / median)`, sy ? `${k(sy.billedTokens.mean)} / ${k(sy.billedTokens.median)}` : '—', re ? `${k(re.billedTokens.mean)} / ${k(re.billedTokens.median)}` : '—', sy?.billedTokens?.mean && re?.billedTokens?.mean ? `${(sy.billedTokens.mean / re.billedTokens.mean).toFixed(2)}×` : '—'], row('Output tokens', 'outputTokens'), row('Run duration s (agent-reported)', 'durationSeconds')] : []),
      row('Assistant turns', 'messages'),
      row('Tool calls', 'toolCalls'),
      row('Build/test iterations', 'iterations'),
      row('…excluding refused commands', 'effectiveIterations'),
      row('Edit rounds', 'editRounds'),
      row('Failed build/test runs', 'failedRuns'),
      row('Lines added vs starter', 'locAdded'),
      ['Wrote own test / kept it', `${sy?.wroteTest ?? 0} / ${sy?.keptTest ?? 0}`, `${re?.wroteTest ?? 0} / ${re?.keptTest ?? 0}`, '—'],
    ])
  )
  P()
  const minShare = Math.min(...analyzed.map((r) => r.attributedShare))
  const meanShare = mean(analyzed.map((r) => r.attributedShare))
  P(`**Phase attribution coverage:** mean ${pct(meanShare)} of each trial's wall time is attributed to a named phase (minimum ${pct(minShare)}${minShare < 0.9 ? `, in ${analyzed.filter((r) => r.attributedShare < 0.9).map((r) => r.trial).join(', ')}` : ''}). The unattributed remainder is time on tools the classifier doesn't know (\`other\`).`)
  P()

  // ---- top time sinks
  P('## Top time sinks: Sygnal vs React')
  P()
  const d = agg.delta
  if (!d.items.length) P('No shared tasks with both arms analyzed; no delta.')
  else {
    P(`Task-matched: for each shared task, Sygnal task mean minus React task mean, then averaged over the ${d.tasks.length} shared tasks. The rows partition wall time (\`tooling-friction\` is split by catalog ID), so they sum to the wall-time delta of **${f1(d.wallDelta)} s per trial**.`)
    P()
    P('**Grouped:**')
    P()
    P(table(['Group', 'Sygnal s/trial', 'React s/trial', 'Δ s/trial', 'Share of Δ', 'Items'], d.buckets.filter((b) => Math.abs(b.delta) >= 0.05 || b.sygnal || b.react).map((b) => [b.bucket, f1(b.sygnal), f1(b.react), `**${f1(b.delta)}**`, pct(b.shareOfDelta), b.items.join(', ')])))
    P()
    P('**Itemized:**')
    P()
    const lbl = (it) => (it.item.startsWith('friction:') ? `friction: ${it.item.slice(9)} — ${CATALOG_BY_ID[it.item.slice(9)]?.title ?? ''}` : it.item.startsWith('learn:') ? `learn: ${it.item.slice(6)}` : `phase: ${it.item.slice(6)}`)
    const items = d.items.filter((it) => Math.abs(it.delta) >= 0.05)
    P(table(['Rank', 'Item', 'Sygnal s/trial', 'React s/trial', 'Δ s/trial', 'Share of Δ'], items.map((it, i) => [i + 1, lbl(it), f1(it.sygnal), f1(it.react), `**${f1(it.delta)}**`, pct(it.shareOfDelta)])))
    P()
    P(sinkNarrative(agg, records))
    P()
  }

  // ---- per task
  P('## Per task and arm')
  P()
  const tRows = []
  for (const t of agg.tasks)
    for (const arm of ['sygnal', 'react']) {
      const s = agg.byTask[t][arm]
      if (!s) continue
      tRows.push([taskLabel(t), arm, `${s.n} (${s.pass}/${s.scored})`, mm(s.wall), `${k(s.peakContext.mean)} / ${k(s.peakContext.median)}`, mm(s.iterations), mm(s.editRounds), f1(s.failedRuns.mean), mm(s.locAdded), `${s.wroteTest}/${s.keptTest}`, s.costUsd?.mean != null ? `${s.costUsd.mean.toFixed(2)}` : '—', k(s.billedTokens?.mean)])
    }
  P(table(['Task', 'Arm', 'n (pass/scored)', 'Wall s', 'Peak ctx tokens', 'Iterations', 'Edit rounds', 'Failed runs', 'LOC added', 'Wrote/kept test', 'Cost (mean)', 'Billed tokens (mean)'], tRows))
  P()
  P('Mean seconds per trial in each phase:')
  P()
  const phRows = []
  for (const t of agg.tasks)
    for (const arm of ['sygnal', 'react']) {
      const s = agg.byTask[t][arm]
      if (s) phRows.push([taskLabel(t), arm, ...PHASE_ORDER.map((p) => f1(s.phases[p])), f1(s.wall.mean)])
    }
  for (const [label, s] of [['**all (shared)**', agg.overallShared], ['**all tasks**', agg.overall]])
    for (const arm of ['sygnal', 'react']) if (s[arm]) phRows.push([label, arm, ...PHASE_ORDER.map((p) => f1(s[arm].phases[p])), f1(s[arm].wall.mean)])
  P(table(['Task', 'Arm', ...PHASE_ORDER, 'wall'], phRows))
  P()

  // ---- catalog
  P('## Friction catalog hits')
  P()
  P('A trial is "affected" if the issue shows up in a failing tool result, in the agent\'s final report, as a known workaround in its commands or final code, or as an API guess in what it wrote (inputs: e.g. G-125 `t.state`). Time cost is the tooling-friction time attributed to the ID (from the failing run to the next green run, plus refused commands for HARNESS-GUARD). Status is read from `dev-plans/PLAN-1-status.md`.')
  P()
  P(
    table(
      ['ID', 'Issue', 'Kind', 'Status', 'Sygnal trials', 'React trials', 'In results / reports / workarounds / inputs', 'Time cost total s', 's per affected trial', 's per Sygnal trial'],
      agg.catalog.map((c) => [c.id, c.title, c.kind, c.status, c.sygnal, c.react, `${c.inResults} / ${c.inReports} / ${c.workarounds} / ${c.inInputs ?? 0}`, f1(c.frictionSecondsTotal), f1(c.frictionSecondsPerAffected), f1(c.frictionSecondsPerSygnalTrial)])
    )
  )
  P()
  P('<details><summary>Trials per catalog ID</summary>\n')
  for (const c of agg.catalog) P(`- **${c.id}**: ${c.trials.join(', ')}`)
  P('\n</details>')
  P()

  // ---- failures
  P('## Failures')
  P()
  P('Failed build/test runs by normalized error signature (refused commands excluded). `cause`: known-defect = matched the catalog; agent-mistake = assertion, syntax or import errors in the agent\'s own code or test; other = unrecognized.')
  P()
  P(table(['Arm', 'Signature', 'Cause', 'Catalog', 'Runs', 'Trials'], agg.failures.signatures.slice(0, 25).map((s) => [s.arm, `\`${s.signature.replace(/`/g, "'")}\``, s.cause, (s.catalog ?? []).join(', ') || '—', s.count, s.trials])))
  P()
  P('Debug episodes (failure → next green run), by cause:')
  P()
  const epRows = []
  for (const arm of ['sygnal', 'react'])
    for (const [cause, x] of Object.entries(agg.failures.episodes[arm])) {
      const n = (arm === 'sygnal' ? agg.overall.sygnal : agg.overall.react)?.n ?? 1
      epRows.push([arm, cause, x.episodes, f1(x.seconds), f1(x.seconds / x.episodes), f1(x.iterations / x.episodes), x.unresolved, f1(x.seconds / n)])
    }
  P(table(['Arm', 'Cause / catalog ID', 'Episodes', 'Total s', 's per episode', 'Runs to green', 'Never green', 's per trial (arm)'], epRows))
  P()
  const fc = agg.failureCategories ?? { sygnal: {}, react: {} }
  const fcRows = []
  for (const arm of ['sygnal', 'react']) for (const [c, e] of Object.entries(fc[arm])) fcRows.push([arm, c, e.manual, e.auto, e.trials.join(', ')])
  if (fcRows.length) {
    P('Failed trials by category (run.md step 5). `manual`: set with `score.mjs --classify`; `auto`: from the sygnal-check findings left in the final code (lib/failure.mjs: SYG104 isolation; SYG101/102/105/110/124/401/410/643 wiring; SYG202/221/222 reducer-shape; SYG301 stream-operator; none: other). Auto categories are suggestions, not written to the results:')
    P()
    P(table(['Arm', 'Category', 'Manual', 'Auto', 'Trials'], fcRows))
    P()
  }

  // ---- skill
  P('## Skill and docs usage (Sygnal arm)')
  P()
  const st = agg.skill
  P(`- Skill tool invoked in **${st.skillInvoked} / ${st.sygnalTrials}** Sygnal trials. Skill text read per trial (incl. the injected SKILL.md): ${mm(st.skillBytes)} bytes (mean / median).`)
  for (const [f, e] of Object.entries(st.files)) P(`- \`${f}\` (${e.fileLines} lines): read in ${e.trials} trials, ${mm(e.linesSeen)} lines seen (mean / median); access: ${Object.entries(e.how).map(([h, n]) => `${h} ×${n}`).join(', ')}.`)
  const os = agg.otherSkills ?? { sygnal: {}, react: {} }
  const osText = ['sygnal', 'react'].map((a) => Object.entries(os[a]).map(([n, k]) => `\`${n}\` ${k} (${a})`).join(', ')).filter(Boolean).join('; ')
  if (osText) P(`- Other skills invoked (the CLI's bundled ones; not counted as skill reads or learn time), trials: ${osText}.`)
  P(`- Reading framework source/docs under \`node_modules\`: Sygnal ${st.libraryReaders.sygnal}/${st.sygnalTrials} trials (${mm(st.libraryBytes.sygnal)} bytes), React ${st.libraryReaders.react}/${(agg.overall.react?.n ?? 0)} trials (${mm(st.libraryBytes.react)} bytes).`)
  P()
  const lt = agg.overallShared.sygnal?.learn ?? agg.overall.sygnal?.learn ?? {}
  const ltr = agg.overallShared.react?.learn ?? agg.overall.react?.learn ?? {}
  const topics = [...new Set([...Object.keys(lt), ...Object.keys(ltr)])].sort((a, b) => (lt[b] ?? 0) - (lt[a] ?? 0))
  if (topics.length) {
    P('**What learning time went to** (mean seconds per trial on the shared tasks, by topic of the learn-phase calls: the Skill call and reading the injected SKILL.md, skill greps, and `node_modules` source reads. Reads made inside a debug or friction span are counted there, not here):')
    P()
    P(table(['Topic', 'Sygnal s/trial', 'React s/trial'], topics.map((t) => [t, f1(lt[t] ?? 0), f1(ltr[t] ?? 0)])))
    P()
  }
  const libFiles = Object.entries(st.library.sygnal.sygnal?.files ?? {}).filter(([f]) => /\.\w+$/.test(f)).sort((a, b) => b[1] - a[1]).slice(0, 14)
  if (libFiles.length) {
    P('Most-read `node_modules/sygnal` files (trials; directory listings excluded):')
    P()
    P(libFiles.map(([f, n]) => `\`${f}\` ${n}`).join(' · '))
    P()
  }
  const otherPkgs = Object.entries(st.library.sygnal).filter(([p]) => p !== 'sygnal').map(([p, e]) => `${p} (${e.trials})`)
  if (otherPkgs.length) P(`Other packages read by Sygnal trials: ${otherPkgs.join(', ')}. React trials: ${Object.entries(st.library.react).map(([p, e]) => `${p} (${e.trials})`).join(', ') || 'none'}.\n`)
  P('**Heatmap: skill sections × trials that saw them.** SKILL.md is injected whole by the Skill tool, so its sections score every invoking trial; `component-patterns.md` sections reflect targeted reads (grep hits with context, sed ranges, Read offsets).')
  P()
  const secRows = []
  for (const [file, f] of Object.entries(skill.files)) {
    for (const s of f.sections) {
      const key = `${file}#${s.heading}`
      const n = st.sections.find((x) => x.section === key)?.trials ?? 0
      const bar = '█'.repeat(Math.round((n / Math.max(1, st.sygnalTrials)) * 20))
      secRows.push([`\`${file}\``, `${'  '.repeat(s.level - 1)}${s.heading}`, `${n}`, bar || '·'])
    }
  }
  P('<details><summary>Full heatmap (all sections)</summary>\n')
  P(table(['File', 'Section', 'Trials', ''], secRows))
  P('\n</details>')
  P()
  const cp = secRows.filter((r) => r[0].includes('component-patterns') && Number(r[2]) > 0).sort((a, b) => Number(b[2]) - Number(a[2]))
  if (cp.length) {
    P('`component-patterns.md` sections actually read (targeted reads only):')
    P()
    P(table(['Section', 'Trials', ''], cp.slice(0, 20).map((r) => [r[1].trim(), r[2], r[3]])))
    P()
  }
  const hasTesting = Object.values(skill.files).some((f) => f.sections.some((s) => /test/i.test(s.heading)))
  P(`The installed skill ${hasTesting ? 'has' : '**has no**'} section about testing.`)
  P()

  // ---- canonical
  P('## Canonical forms in Sygnal solutions')
  P()
  const ct = agg.canonical
  const lab = { shorthandKeys: "`'ACTION | SINK'` shorthand keys (C5, non-canonical)", emitCalls: '`emit(...)` (C6, non-canonical)', eventCalls: '`event(...)` (C6, canonical; not in the baseline build)', rawEventsObjects: 'raw `EVENTS: s => ({ type, data })` (C6, non-canonical)', childSelectString: "`CHILD.select('Name')` string (C7, non-canonical)", childSelectFn: '`CHILD.select(Component)` (C7, canonical)', positionalView: 'positional view args `(props, state, ...)` (C1, non-canonical)', abortReturns: '`ABORT` uses (C3)', effectSinks: '`EFFECT:` sinks (C4)' }
  P(table(['Form', 'Occurrences', `Trials (of ${ct.trials})`], Object.entries(ct.forms).map(([key, v]) => [lab[key] ?? key, v.total, v.trials])))
  P()
  const diagEntries = Object.entries(ct.sygnalCheck)
  P(`**sygnal-check on final \`src/\`:** ${diagEntries.length ? diagEntries.map(([code, ts]) => `${code} in ${ts.length} trial(s) (${ts.join(', ')})`).join('; ') : `no diagnostics in any of ${ct.trials} trials`}.${ct.checkErrors.length ? ` Checker errors: ${ct.checkErrors.join(', ')}.` : ''}`)
  P()
  const appr = {}
  for (const r of records.filter((x) => x.keptTests?.length)) for (const a of r.testApproach) (appr[`${r.arm}: ${a}`] ??= []).push(r.trial)
  P(`**Kept test files and how they drive the app:** ${Object.entries(appr).map(([a, ts]) => `${a} ×${ts.length}`).join('; ') || 'none kept'}.`)
  P()

  // ---- self reported
  P("## Agents' self-reported issues")
  P()
  const byId = {}
  for (const r of records) for (const id of r.catalog?.report ?? []) (byId[id] ??= []).push(r.trial)
  P(table(['Catalog ID', 'Trials whose final report names it'], Object.entries(byId).sort((a, b) => b[1].length - a[1].length).map(([id, ts]) => [`${id} — ${CATALOG_BY_ID[id]?.title ?? ''}`, `${ts.length}: ${ts.join(', ')}`])))
  P()
  P('<details><summary>Extracted complaint sentences, per trial</summary>\n')
  for (const r of records.filter((x) => x.selfReported?.length)) {
    P(`**${r.trial}**`)
    for (const s of r.selfReported) P(`- ${s}`)
    P()
  }
  P('</details>')
  P()

  // ---- recommendations
  P('## Recommendations')
  P()
  const { active: recs, suppressed } = recommendationSet(agg, records, skill, docs)
  P('Each recommendation was checked against the installed skill, llms.txt and the trackers first; ones already done are listed after the list.')
  P()
  recs.forEach((r, i) => {
    P(`${i + 1}. **${r.title}** ${r.target ? `_(${r.target})_` : ''}${r.status === 'rewritten' ? ' _(rewritten: precondition already met)_' : ''}`)
    if (r.precondition) P(`   *Checked:* ${r.precondition}.`)
    P(`   ${r.change}`)
    P(`   *Evidence:* ${r.evidence}`)
    P()
  })

  if (suppressed.length) {
    P('**Suppressed (already done):**')
    P()
    for (const x of suppressed) P(`- ${x.title.replace(/[.:]$/, '')}: ${x.reason}.`)
    P()
  }

  // ---- method
  P('## Method and limits')
  P()
  P('**Phase attribution.** Every interval between two consecutive transcript events (tool call, tool result, assistant text) is given to the later event: generating a tool call and running it both count toward that call\'s phase; planning text in the same message counts toward the message\'s first call. Phases:')
  P()
  for (const [p, doc] of PHASE_DOC) P(`- \`${p}\`: ${doc}.`)
  P()
  P('Limits:')
  P('- Model "thinking" before a call is charged to that call. The cost of ingesting a large tool result (e.g. the 12 KB skill injection) lands on the *next* call, usually `orient`. So `learn` undercounts the skill\'s real cost; the context-token rows capture the rest.')
  P('- `debug` / `tooling-friction` start at the failed run and end at the next run that passes and was issued after the failure. Deleting a failing test and re-running counts as green. A failure that is never followed by a green run is charged to the end of the trial (column "Never green").')
  P('- Pass/fail of a run is read from vitest / vite summaries first, then the exit code (output is often piped through `tail`, which hides it).')
  P("- Catalog matching is regex-based. 'suspect' entries (G-015, G-016: `waitForState timed out`) count as friction only when the agent's report names the issue; otherwise they are agent-mistake debug time. Report matching can also pick up mentions that aren't complaints (e.g. explaining the isolation trap in task 07).")
  if (meta.methods?.includes('headless')) P('- **Headless trials** (run-trial.mjs): cost, billed tokens (input + output + cache read + cache creation over all turns), output tokens and the agent-reported duration come from the run\'s final `result` event, so they are exact. Billed tokens are much larger than peak context, because every turn re-reads the cached context.')
  P('- **Output tokens are not reliable in subagent transcripts**: each streamed message records a partial `output_tokens` (often 16). Context size (input + cache read + cache creation) is reliable, so the token metric used is peak context per trial (≈ the final context the Agent tool reports), plus cache-creation tokens (new tokens entering context).')
  P('- Wall time is first to last transcript timestamp; it matches the recorded `wallSeconds` within a second for all but a few trials.')
  if (!meta.methods?.length || meta.methods.some((m) => m !== 'headless')) P('- HARNESS-GUARD is an artifact of how trials were spawned (subagents inherit the coordinator\'s worktree guard), not of either framework. It costs both arms, more for Sygnal because Sygnal agents run more compound commands.')
  P('- Small n (5 trials per task and arm); differences under ~5 s per trial are within noise.')
  P(processKillNote(records))
  P(skillGuardNote(records))
  P()

  // ---- appendix
  P('## Appendix: per-trial')
  P()
  P(
    table(
      ['Trial', 'Pass', 'Wall s', 'Attr.', 'Peak ctx', 'Iter', 'ER', ...PHASE_ORDER.map((p) => p.replace('tooling-friction', 'friction').replace('test-authoring', 'tests')), 'Friction IDs'],
      analyzed.map((r) => [r.trial, r.scored ? (r.scored.pass ? '✓' : '✗') : '?', f1(r.wallSeconds), pct(r.attributedShare), k(r.tokens.peakContext), r.iterations, r.editRounds, ...PHASE_ORDER.map((p) => f0(r.phases[p] ?? 0)), Object.entries(r.frictionSeconds).map(([id, s]) => `${id} ${f0(s)}`).join(', ') || '—'])
    )
  )
  P()
  return out.join('\n')
}

function sinkNarrative(agg, records) {
  const d = agg.delta
  const top = d.items.filter((x) => x.delta > 0).slice(0, 4)
  const parts = top.map((it) => `${it.item.replace(':', ' ')} (+${f1(it.delta)} s, ${pct(it.shareOfDelta)})`)
  const tb = d.buckets.filter((b) => b.bucket.startsWith('self-testing')).reduce((a, b) => a + b.delta, 0)
  const fr = d.items.filter((x) => x.item.startsWith('friction:') && x.item !== 'friction:HARNESS-GUARD')
  const frSum = fr.reduce((a, x) => a + x.delta, 0)
  const lsum = d.items.filter((x) => x.item.startsWith('learn:')).reduce((a, x) => a + x.delta, 0)
  const learn = lsum ? { delta: lsum } : null
  const ta = d.items.find((x) => x.item === 'phase:test-authoring')
  return `The largest single items are ${parts.join(', ')}. Everything to do with the agents testing their own work in Sygnal (tooling defects, learning the test tooling, writing tests) adds up to **${f1(tb)} s per trial (${pct(d.wallDelta ? tb / d.wallDelta : null)} of the delta)**. Known framework/tooling defects (catalog friction excluding the harness guard) explain **${f1(frSum)} s** per trial (${pct(d.wallDelta ? frSum / d.wallDelta : null)} of the delta)${learn ? `; learning the framework (skill + library source) explains ${f1(learn.delta)} s` : ''}${ta ? `; writing the agent's own tests ${f1(ta.delta)} s` : ''}.`
}

/**
 * G-127: trials whose agent ran machine-wide process kills (pkill, killall, `xargs kill`, kill by lookup).
 * Those can have killed other concurrent trials' dev servers and test runs, or the orchestrator, so the
 * run's other trials may be contaminated too (lost runs, timeouts, odd test failures).
 */
export function processKillNote(records) {
  const wide = records.filter((r) => r.processKills?.some((k) => k.machineWide))
  const hit = wide.filter((r) => !r.processGuard)
  const blocked = wide.filter((r) => r.processGuard)
  const nine = records.filter((r) => r.processKills?.length && !r.processKills.some((k) => k.machineWide))
  const fmt = (r) => {
    const ks = r.processKills.filter((k) => k.machineWide)
    return `${r.trial} (${ks.length}: ${[...new Set(ks.map((k) => k.kind))].join(', ')})`
  }
  const lines = []
  if (!wide.length) lines.push('- **Process kills** (G-127): no trial ran a machine-wide process kill (pkill, killall, `xargs kill`, kill by lookup).')
  if (hit.length) lines.push(`- **Process kills** (G-127): ${hit.length} unguarded trial(s) ran machine-wide process kills, which hit every matching process on the machine (other concurrent trials' dev servers and test runs, the orchestrator): ${hit.map(fmt).join('; ')}. Trials of this run that overlapped them may be contaminated (killed test runs, timeouts, lost trials). Trials run with the process guard (\`processGuard: 1\` in the run meta and manifest) have these commands refused.`)
  if (blocked.length) lines.push(`- **Process kills refused by the guard** (G-127, \`processGuard: 1\`): ${blocked.map(fmt).join('; ')}. No other process was affected; the attempt costs that trial a refused call.`)
  if (nine.length) lines.push(`- \`kill -9\` by PID (the trial's own process, not machine-wide): ${nine.map((r) => r.trial).join(', ')}.`)
  return lines.join('\n')
}

/**
 * D234: were Claude Code's built-in skills (`run`, `dataviz`, ...) available to the trials? A condition
 * change between runs (`skillGuard` in the run meta and manifest; absent = 0, available).
 */
export function skillGuardNote(records) {
  const on = records.filter((r) => r.skillGuard)
  const off = records.length - on.length
  if (!on.length) return "- **Built-in skills** (D234): available in every trial (`skillGuard` 0, the condition before 4-E2): agents could call the CLI's own skills (`run`, `dataviz`, …); the calls are listed under \"Other skills invoked\". Runs from 4-E2 on block them, so compare such numbers across that change with care."
  if (!off) return '- **Built-in skills** (D234): blocked in every trial (`skillGuard: 1`: `disableBundledSkills`, `skillOverrides` off and `Skill()` deny rules in each trial\'s settings); the only skill a trial sees is its variant\'s.'
  return `- **Built-in skills** (D234): **mixed conditions**: blocked in ${on.length} trial(s) (\`skillGuard: 1\`), available in ${off} (\`skillGuard\` 0, before 4-E2). Compare the two groups with care.`
}
