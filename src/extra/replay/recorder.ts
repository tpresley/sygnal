// sygnal/replay: the recorder. A hook layer (src/core/hooks.ts) registered on the dev bridge
// (globalThis.__SYGNAL_DIAGNOSTICS__.layers), as sygnal/devtools' action log is: the core calls no
// recorder code and an app that doesn't import sygnal/replay pays nothing. It records the first
// app started after startRecording() (run() or renderComponent()).
//
// The log (format version 1; RECORDING_SCHEMA in ./schema.ts has every field):
//   kind, version   'sygnal-recording', 1
//   sygnal          the Sygnal version that recorded it (a replay on another one warns, Q8)
//   app             the root component's name
//   components      component name -> the action names its model handles (a replay against code
//                   without one of them warns, Q8)
//   init            the root state when the app started (after INITIALIZE)
//   sources         the app's source names that aren't built in: 'resources' (makeFetchDriver),
//                   'timers' (makeTimerDriver), else 'other' (the replay gives those an inert driver)
//   p               the instance addresses (./address.ts); actions point into it
//   a               every action, in queue order: { s: seq, t: ms since the previous one (at
//                   enqueue: onDispatch), p, y: type, c: cause code, r: a reply's source, d: data
//                   (inputs only, ./format.ts encode), e: the clock / randomness its handlers
//                   read, h: hash of the instance's new state (when its STATE changed), f: the
//                   hashes of the values its other sinks produced, [sink, hash] }
//   k               checkpoints, one per patch (Q6): { s: the last action before it, v: vnode
//                   hash, o: the root state's diff from the previous one }
//   fx              declaration statics sent to drivers (resources, timers, ...), [seq, sink, hash]
//   end             the final root state's diff from the last checkpoint, and the session's length
//
// Inputs (the replay dispatches them from the log): causes intent, reply, next, simulateAction,
// behavior, agent, setState (7.2: the runtime API's setState goes through onAction).
// Consequences (regenerated by the code under replay; recorded without data so the replay can
// compare them): built-in (INITIALIZE, BOOTSTRAP, DISPOSE) and parent.
import {encode, plain, diff, vnodeString, fnv, mask, maskAll, redactInput, stable, isTextEntry, clone} from './format'
import {withEntropy, recordInto, props as entropyProps} from './entropy'
import {addresses} from './address'
import {VERSION} from './version'
import {replayTest, type ReplayTestOptions} from './report'

export const CAUSE: Record<string, string> = {intent: 'i', reply: 'r', next: 'n', simulateAction: 'a', behavior: 'B', agent: 'g', setState: 'S', 'built-in': 'b', parent: 'p'}
export const CAUSE_NAME: Record<string, string> = {i: 'intent', r: 'reply', n: 'next', a: 'simulateAction', B: 'behavior', g: 'agent', S: 'setState', b: 'built-in', p: 'parent'}
export const INPUT = /*#__PURE__*/ new Set(['i', 'r', 'n', 'a', 'B', 'g', 'S'])
const STANDARD = /^(DOM|EVENTS|STATE|LOG|CHILD|PARENT|READY|props\$|children\$|dispose\$|commands\$|__.*)$/

const G: any = globalThis
/** the layer's clock (performance.now when there is one), read outside any handler */
const clock = () => (G.performance ? G.performance.now() : Date.now())

export interface RecordOptions {
  /**
   * On by default (Q7 of the research: anything that leaves the machine). `true` or
   * `{ keep, also }`: by provenance, the strings of intent actions dispatched while a text-entry
   * DOM event is delivered (an input / keydown in a text field, a form submit; the DOM drivers
   * report the event to the core's onDispatch hook), of later actions of a type once dispatched
   * that way, of reply actions (server data; not a timer's: its tick, a frame's sampled keys), of setState values, and of the types in `also` are
   * pseudonymized (same shape, equal strings stay equal); never those in `keep`, nor next() data
   * (the code's own). Checkpoints are stored and compared on masked values. A redacted string the
   * model branches on (a route name) makes the replay diverge at that action: add it to `keep`.
   * `false`: nothing redacted.
   */
  redact?: boolean | {keep?: string[]; also?: string[]}
  /**
   * On by default: leave out input actions that changed nothing (no state change, no sink value,
   * no EFFECT, no clock / randomness read), e.g. an idle timer's ticks. A replay of the same code
   * is unaffected; if new code would make such an action do something, the replay doesn't send it
   */
  dropNoops?: boolean
  /** 'hash' (default), or 'html': each checkpoint also keeps the markup (for reports) */
  vnodes?: 'hash' | 'html'
}

export interface Recorder {
  /** stop recording; the log (undefined when no app started) */
  stop(): any
  /** the log so far, finished as stop() would (the recording goes on) */
  log(): any
  /** recording now (an app started, not stopped) */
  active(): boolean
  /** a replay test for the log so far: the test file and the recording's JSON (Copy as test's replay mode) */
  test(options?: ReplayTestOptions): {code: string; recording: string; file: string}
}

/** Start recording the next app (run() or renderComponent()). */
export function startRecording(options: RecordOptions = {}): Recorder {
  const {redact = true, dropNoops = true, vnodes = 'hash'} = options
  const D = (G.__SYGNAL_DIAGNOSTICS__ ||= {})
  const L = (D.layers ||= new Set())
  let log: any = null
  let stopped = false
  let api: any = null
  let finish: (() => any) | undefined
  const keep = new Set((typeof redact == 'object' && redact.keep) || [])
  const textTypes = new Set((typeof redact == 'object' && redact.also) || [])
  const salt = Math.random().toString(36).slice(2)
  const norm = redact ? (v: any) => maskAll(plain(v)) : plain
  const h = (v: any) => fnv(stable(norm(v)))
  const text = redact ? mask : undefined

  const factory = (a: any) => {
    if (log || stopped) return {}
    api = a
    const addr = addresses()
    const paths = new Map<string, number>()
    const pathIdx = (p: string) => {
      let i = paths.get(p)
      if (i === undefined) { i = log.p.length; paths.set(p, i!); log.p.push(p) }
      return i!
    }
    let seq = 0
    let last = clock()
    const t0 = last
    let cur: any = null       // the action whose handlers run now
    let prevState: any        // the root state at the last checkpoint (normalized)
    let dropped = 0
    let prevLast = last
    // onDispatch -> onAction: the queue is FIFO, so an action's dispatch record is the first
    // pending one of its instance, type and data (those before it never ran: a disposed instance)
    const pending: Array<{id: number; type: string; data: any; t: number; text: boolean}> = []

    log = {kind: 'sygnal-recording', version: 1, sygnal: VERSION, app: undefined, recorded: new Date().toISOString(), redacted: !!redact,
      components: {}, sources: {}, init: undefined, p: [], a: [], k: [], fx: []}

    const finishCur = () => {
      if (!cur) return
      const x = cur
      cur = null
      if (dropNoops && INPUT.has(x.c) && !x.h && !x.f && !x.e && !x.x && log.a[log.a.length - 1] === x) {
        log.a.pop()
        dropped++
        last = prevLast   // the next entry's `t` counts from the last one kept
      }
      delete x.x
    }

    const hooks = {
      onCreate(iv: any) {
        const p = addr.create(iv)
        if (!(iv.name in log.components)) log.components[iv.name] = [...iv.def.handlers.keys()].sort()
        if (iv.isRoot && log.app === undefined) {
          log.app = iv.name
          // (unmasked even when redacting: it is the code's initialState or run()'s)
          log.init = plain(api.getState())
          for (const [n, s] of Object.entries<any>(iv.sources || {})) {
            if (STANDARD.test(n)) continue
            log.sources[n] = s && s.__sygnalStatic === 'resources' ? 'resources' : s && s.__sygnalStatic === 'timers' ? 'timers' : 'other'
          }
          prevState = norm(log.init)
        }
        pathIdx(p)
      },
      onDispose(iv: any) { addr.dispose(iv) },
      onDispatch(iv: any, type: string, data: any, cause: string, event: any) {
        if (stopped) return
        pending.push({id: iv.id, type, data, t: clock(), text: !!redact && cause == 'intent' && isTextEntry(event)})
      },
      onAction(iv: any, action: any) {
        if (stopped) return
        finishCur()
        let t = clock(), typed = false
        const i = pending.findIndex(d => d.id === iv.id && d.type === action.type && d.data === action.data)
        if (i >= 0) { t = pending[i].t; typed = pending[i].text; pending.splice(0, i + 1) }
        const c = CAUSE[action.cause] || action.cause
        const entry: any = {s: ++seq, t: Math.max(0, Math.round(t - last)), p: pathIdx(addr.of(iv)), y: action.type, c}
        if (c == 'r' && action.source) entry.r = action.source
        prevLast = last
        last = Math.max(last, t)
        if (INPUT.has(c) && action.data !== undefined) {
          // an intent over the instance's own STATE stream: replayed with its current state
          if (c == 'i' && isEcho(action.data, iv.state)) entry.d = {$echo: 1}
          else {
            let d = encode(action.data)
            if (typed) textTypes.add(action.type)
            // (a timer's reply is the app's own data, not a server's: its tick, a frame's sampled
            // buttons, which the app named; canvas-game)
            const server = c == 'r' && log.sources?.[action.source] !== 'timers'
            if (redact && !keep.has(action.type) && (server || c == 'S' || textTypes.has(action.type))) d = redactInput(d, salt)
            entry.d = d
          }
        }
        // a setState runs no handler: it is its own state change
        if (c == 'S') entry.h = h(action.data)
        log.a.push(entry)
        cur = c == 'S' ? null : entry
      },
      wrapHandler(_iv: any, _type: string, sink: string, fn: any) {
        const entry = cur
        if (stopped || typeof fn != 'function' || !entry) return
        // (the list is made on the first read: an async EFFECT's reads after an `await` land here too)
        const take = recordInto(x => (entry.e ||= []).push(x))
        return (s: any, d: any, n: any, p: any, ...rest: any[]) => {
          if (sink == 'EFFECT') entry.x = 1
          return withEntropy(take, () => fn(s, d, n, entropyProps(p, take), ...rest))
        }
      },
      onReducer(_iv: any, _type: string, _prev: any, next: any) {
        if (!stopped && cur) cur.h = h(next)
      },
      onSink(_iv: any, type: string | null, sink: string, value: any) {
        if (stopped) return
        if (type === null) { log.fx.push([seq, sink, h(value)]); return }
        if (cur) (cur.f ||= []).push([sink, h(value)])
      },
      onPatch(vnode: any) {
        if (stopped) return
        finishCur()
        const s = norm(api.getState())
        const cp: any = {s: seq, v: fnv(vnodeString(vnode, text))}
        const o = diff(prevState, s)
        if (o.length) cp.o = o
        if (vnodes == 'html') cp.html = vnodeString(vnode, text)
        prevState = s
        log.k.push(cp)
      },
    }
    finish = () => {
      finishCur()
      const o = diff(prevState, norm(api.getState()))
      return {s: seq, ms: Math.round(clock() - t0), dropped, ...(o.length ? {o} : {})}
    }
    return hooks
  }
  L.add(factory)
  const self: Recorder = {
    log: () => log && (stopped ? log : clone({...log, end: finish!()})),
    active: () => !!log && !stopped,
    stop() {
      L.delete(factory)
      if (log && !stopped) log.end = finish!()
      stopped = true
      if (D.recorder === self) D.recorder = undefined
      return log ?? undefined
    },
    test(o) {
      const l = self.log()
      if (!l) throw new Error('[sygnal/replay] nothing recorded yet: startRecording() before run()')
      const file = `${l.app}.recording.json`
      return {code: replayTest(l, {logFile: './' + file, ...o}), recording: JSON.stringify(l), file}
    },
  }
  // sygnal/devtools' Copy as test (replay mode) reads the newest recorder from the bridge
  D.recorder = self
  return self
}

/** the data is the instance's own state (an intent over STATE.stream; calculated fields may be added) */
function isEcho(data: any, state: any) {
  if (!data || !state || typeof data != 'object' || typeof state != 'object' || Array.isArray(data)) return false
  if (data === state) return true
  const keys = Object.keys(state)
  return keys.length > 0 && keys.every(k => data[k] === state[k])
}
