/**
 * PLAN-10 P-1: the graph page (sygnal-check/src/graphView/) as the files of the devtools panel's App
 * graph frame. An extension page runs no inline script (MV3's CSP, which can't be relaxed), so the
 * markup comes from graphHtml() with its inline <style> and <script> moved to files, and a CSP that
 * allows only the extension's own scripts: the frame loads nothing remote and connects nowhere.
 *
 *   graphFrameFiles() → { 'graph.html', 'graph-page.css', 'graph-page.js' }
 *
 * Used by devtools/build.mjs; test/p10-devtools-graph.test.js and the browser suite build with it.
 */
import { fileURLToPath, pathToFileURL } from 'node:url'
import { resolve, dirname } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

export const GRAPH_FRAME_CSP = "default-src 'none'; style-src 'self' 'unsafe-inline'; script-src 'self'; img-src data: blob:; base-uri 'none'; form-action 'none'"

export async function graphFrameFiles() {
  const { graphHtml, pageAssets } = await import(pathToFileURL(resolve(root, 'sygnal-check/src/graphView/html.js')).href)
  const empty = { version: 1, source: 'runtime', components: [], events: {}, diagnostics: [] }
  let html = graphHtml(empty, { title: 'App graph', codes: {} })
  const swap = (re, to, what) => {
    const next = html.replace(re, () => to)
    if (next === html) throw new Error(`devtools graph frame: ${what} not found in graphHtml()'s page`)
    html = next
  }
  swap(/<meta http-equiv="Content-Security-Policy" content="[^"]*">/, `<meta http-equiv="Content-Security-Policy" content="${GRAPH_FRAME_CSP}">`, 'the CSP meta')
  swap(/<style>[\s\S]*?<\/style>/, '<link rel="stylesheet" href="graph-page.css">', 'the <style>')
  swap(/<script type="application\/json" id="graph-data">[\s\S]*?<\/script>\s*<script type="application\/json" id="graph-meta">[\s\S]*?<\/script>\s*<script>[\s\S]*?<\/script>/,
    '<script src="graph-page.js"></script>\n<script src="graph-frame.js"></script>', 'the data and page scripts')
  const { css, js } = pageAssets()
  return {
    'graph.html': html,
    'graph-page.css': css,
    'graph-page.js': `// generated by devtools/build.mjs from sygnal-check/src/graphView/ (PLAN-10 P-1); do not edit\nwindow.__sygnalGraphV = (() => {\n'use strict'\nconst V = {}\n${js}\nreturn V\n})()\n`,
  }
}
