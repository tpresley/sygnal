#!/usr/bin/env node
// Results of the agent-docs comparison runs (evals/agent-ergonomics/results/agent-docs-*): per-arm
// numbers, and each arm against its control, paired by task. A task's score is the mean log of its
// trials; the effect is the mean across tasks of (arm - control), shown as a ratio. The interval
// resamples tasks (seeded bootstrap), the p value is the exact sign-flip test over tasks.
// Writes data/results.md and data/results.json.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const results = path.resolve(here, '../../../../evals/agent-ergonomics/results')
const RUNS = {
  sonnet: { control: 'current', arms: ['current', 'compact', 'index'], run: (a) => `agent-docs-${a}-sonnet` },
  haiku: { control: 'current', arms: ['current', 'compact'], run: (a) => `agent-docs-${a}-haiku` },
  pilot: { control: 'current', arms: ['current', 'compact'], run: (a) => `agent-docs-pilot-${a}-haiku` },
  skill: { control: 'current-skill', arms: ['current-skill', 'compact-skill'], run: (a) => `agent-docs-${a}-sonnet` },
}
const METRICS = {
  costUsd: (t) => t.costUsd, billedTokens: (t) => t.tokens, wallSeconds: (t) => t.wallSeconds,
  peakContext: (t) => t.a.tokens.peakContext, outputTokens: (t) => t.outputTokens,
  toolCalls: (t) => t.a.toolCalls.total, iterations: (t) => t.a.iterations,
  docBytesRead: (t) => t.a.skill.libraryBytes,
}
// Counts that can be zero stay out of the log ratios; they are reported as means.
const LOG = ['costUsd', 'billedTokens', 'wallSeconds', 'peakContext', 'outputTokens', 'toolCalls', 'docBytesRead']

const read = (f) => JSON.parse(fs.readFileSync(path.join(results, f), 'utf8'))
function load(run) {
  const scored = read(`${run}.json`)
  const analysed = new Map(read(`analysis/${run}.json`).trials.map((t) => [`${t.task}/${t.trialNo}`, t]))
  return scored.map((t) => ({ ...t, a: analysed.get(`${t.task}/${t.trial}`) }))
}
const mean = (a) => a.reduce((s, x) => s + x, 0) / a.length
const sd = (a) => { const m = mean(a); return a.length < 2 ? 0 : Math.sqrt(a.reduce((s, x) => s + (x - m) ** 2, 0) / (a.length - 1)) }
const median = (a) => { const s = [...a].sort((x, y) => x - y); const n = s.length; return n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2 }
const byTask = (ts) => { const m = new Map(); for (const t of ts) (m.get(t.task) ?? m.set(t.task, []).get(t.task)).push(t); return m }

function rng(seed) { return () => (seed = (seed * 1664525 + 1013904223) >>> 0) / 2 ** 32 }
function pairedEffect(control, arm, f) {
  const c = byTask(control), a = byTask(arm)
  const tasks = [...c.keys()].filter((k) => a.has(k))
  const taskLog = (ts) => mean(ts.map((t) => Math.log(f(t))))
  const d = tasks.map((k) => taskLog(a.get(k)) - taskLog(c.get(k)))
  const r = rng(20261110), boots = []
  for (let i = 0; i < 20000; i++) boots.push(mean(d.map(() => d[Math.floor(r() * d.length)])))
  boots.sort((x, y) => x - y)
  const obs = Math.abs(mean(d))
  let extreme = 0
  for (let mask = 0; mask < 2 ** d.length; mask++) {
    if (Math.abs(mean(d.map((x, i) => (mask >> i) & 1 ? -x : x))) >= obs - 1e-12) extreme++
  }
  return {
    ratio: Math.exp(mean(d)), low: Math.exp(boots[Math.floor(boots.length * 0.025)]), high: Math.exp(boots[Math.floor(boots.length * 0.975)]),
    p: extreme / 2 ** d.length, tasks: d.length, down: d.filter((x) => x < 0).length, min: Math.exp(Math.min(...d)), max: Math.exp(Math.max(...d)),
  }
}
// The trial-to-trial spread of a metric within one task, pooled across tasks (log scale, so 0.25 is about ±25 %).
function withinTaskSd(ts, f) {
  let ss = 0, df = 0
  for (const group of byTask(ts).values()) {
    const logs = group.map((t) => Math.log(f(t))), m = mean(logs)
    ss += logs.reduce((s, x) => s + (x - m) ** 2, 0); df += logs.length - 1
  }
  return df ? Math.sqrt(ss / df) : 0
}
// Wilson 95 % interval for a pass rate.
function wilson(k, n) {
  const z = 1.96, p = k / n, d = 1 + z * z / n, c = (p + z * z / (2 * n)) / d, h = (z * Math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))) / d
  return [Math.max(0, c - h), Math.min(1, c + h)]
}

const fmt = {
  costUsd: (x) => `$${x.toFixed(3)}`, billedTokens: (x) => `${Math.round(x / 1000)}k`, wallSeconds: (x) => `${x.toFixed(1)} s`,
  peakContext: (x) => `${(x / 1000).toFixed(1)}k`, outputTokens: (x) => `${Math.round(x / 1000 * 10) / 10}k`,
  toolCalls: (x) => x.toFixed(1), iterations: (x) => x.toFixed(1), docBytesRead: (x) => `${(x / 1000).toFixed(1)} KB`,
}
const pct = (x) => `${(100 * x).toFixed(0)}%`
const out = [], json = {}
const say = (s = '') => out.push(s)
say('Generated by `tools/results.mjs` from `evals/agent-ergonomics/results/agent-docs-*`. Do not edit.\n')
for (const [name, cfg] of Object.entries(RUNS)) {
  const data = Object.fromEntries(cfg.arms.map((a) => [a, load(cfg.run(a))]))
  json[name] = { arms: {}, effects: {} }
  say(`## ${name}\n`)
  say('| Arm | Trials | Pass | Pass 95% | Hidden tests | Total cost | ' + Object.keys(METRICS).map((m) => `${m} mean (median, sd)`).join(' | ') + ' |')
  say('|---|---|---|---|---|---|' + Object.keys(METRICS).map(() => '---').join('|') + '|')
  for (const [arm, ts] of Object.entries(data)) {
    const pass = ts.filter((t) => t.pass).length, [lo, hi] = wilson(pass, ts.length)
    const hp = ts.reduce((s, t) => s + t.testsPassed, 0), ht = ts.reduce((s, t) => s + t.testsTotal, 0), total = ts.reduce((s, t) => s + t.costUsd, 0)
    json[name].arms[arm] = { trials: ts.length, pass, wilson: [lo, hi], hiddenPassed: hp, hiddenTotal: ht, totalCost: total, metrics: {} }
    const cells = Object.entries(METRICS).map(([m, f]) => {
      const v = ts.map(f)
      json[name].arms[arm].metrics[m] = { mean: mean(v), median: median(v), sd: sd(v), withinTaskLogSd: LOG.includes(m) && v.every((x) => x > 0) ? withinTaskSd(ts, f) : null }
      return `${fmt[m](mean(v))} (${fmt[m](median(v))}, ${fmt[m](sd(v))})`
    })
    say(`| ${arm} | ${ts.length} | ${pass} | ${pct(lo)}–${pct(hi)} | ${hp}/${ht} | $${total.toFixed(2)} | ${cells.join(' | ')} |`)
  }
  say()
  say('Within-task trial spread (pooled log SD): ' + cfg.arms.map((a) => `${a}: ` + ['costUsd', 'billedTokens', 'wallSeconds', 'peakContext'].map((m) => `${m} ${json[name].arms[a].metrics[m].withinTaskLogSd.toFixed(2)}`).join(', ')).join('; ') + '\n')
  const pairs = cfg.arms.filter((a) => a !== cfg.control).map((a) => [cfg.control, a])
  if (cfg.arms.includes('index')) pairs.push(['compact', 'index'])
  for (const [c, a] of pairs) {
    say(`### ${a} / ${c} (paired by task)\n`)
    say('| Metric | Ratio | 95% (tasks bootstrapped) | Exact sign-flip p | Tasks lower | Per-task range |')
    say('|---|---|---|---|---|---|')
    for (const m of LOG) {
      if (![...data[c], ...data[a]].every((t) => METRICS[m](t) > 0)) { say(`| ${m} | (a zero value: not computed) | | | | |`); continue }
      const e = pairedEffect(data[c], data[a], METRICS[m])
      json[name].effects[`${a}/${c}/${m}`] = e
      say(`| ${m} | ${e.ratio.toFixed(2)} | ${e.low.toFixed(2)}–${e.high.toFixed(2)} | ${e.p.toFixed(4)} | ${e.down}/${e.tasks} | ${e.min.toFixed(2)}–${e.max.toFixed(2)} |`)
    }
    say()
  }
  say('### Per task: mean cost, peak context, passes\n')
  say('| Task | ' + cfg.arms.map((a) => `${a} cost / peak / pass`).join(' | ') + ' |')
  say('|---|' + cfg.arms.map(() => '---').join('|') + '|')
  for (const task of byTask(data[cfg.control]).keys()) {
    say(`| ${task} | ` + cfg.arms.map((a) => {
      const ts = data[a].filter((t) => t.task === task)
      return `${fmt.costUsd(mean(ts.map((t) => t.costUsd)))} / ${fmt.peakContext(mean(ts.map(METRICS.peakContext)))} / ${ts.filter((t) => t.pass).length}/${ts.length}`
    }).join(' | ') + ' |')
  }
  say()
}
// The skill arms against the no-skill arms on the same 15 tasks (3 trials per task without a skill, 2 with).
say('## Skill arms against no-skill arms (Sonnet, paired by task)\n')
json.across = {}
for (const [c, a] of [['current', 'current-skill'], ['compact', 'compact-skill'], ['current', 'compact-skill']]) {
  const control = load(`agent-docs-${c}-sonnet`), arm = load(`agent-docs-${a}-sonnet`)
  say(`### ${a} / ${c}\n`)
  say('| Metric | Ratio | 95% (tasks bootstrapped) | Exact sign-flip p | Tasks lower | Per-task range |')
  say('|---|---|---|---|---|---|')
  for (const m of LOG) {
    if (![...control, ...arm].every((t) => METRICS[m](t) > 0)) { say(`| ${m} | (a zero value: not computed) | | | | |`); continue }
    const e = pairedEffect(control, arm, METRICS[m])
    json.across[`${a}/${c}/${m}`] = e
    say(`| ${m} | ${e.ratio.toFixed(2)} | ${e.low.toFixed(2)}–${e.high.toFixed(2)} | ${e.p.toFixed(4)} | ${e.down}/${e.tasks} | ${e.min.toFixed(2)}–${e.max.toFixed(2)} |`)
  }
  say()
}
// What each trial opened, from the agents' own tool inputs in the transcripts (the analysis' file list misses
// `cd node_modules/sygnal; cat llms/x.md`). The transcripts live in the run's trial directory, not in the repository.
const TRIALS = '/private/tmp/sygnal-evals/trials'
const AI = /llms\/ai\.md|guide\/(ai-|agent)/, RES = /llms\/resources\.md|guide\/resources/, UI = /llms\/ui\.md/
const TRIGGER = {
  '10': /llms\/ui\.md|wizards\.md/, '11': /llms\/(http|resources)\.md|guide\/(http|resources)/, '23': RES, '24': RES, '25': /llms\/router\.md|guide\/router/,
  '30': /llms\/forms\.md|forms(-reference)?\.md/, '31': /llms\/ui\.md|guide\/ui\/|ui\/(menu|combobox)/, '33': /llms\/ui\.md|virtual-collections/, '34': /llms\/ui\.md|drag-and-drop/,
  '44': AI, '45': AI, '46': AI, '48': AI, '49': AI,
}
const OPENED = {
  'called the skill': /"skill":"sygnal-dev"/, 'llms.txt': /llms\.txt/, 'a topic file': /llms\/[a-z-]+\.md|llms\/\*/, 'a guide page': /guide\/[\w/-]+\.md/,
  'dist/index.d.ts': /index\.d\.ts/, 'built JS or the package src': /dist\/[\w.-]+\.[mc]?js\b|sygnal\/src\b/,
}
function toolInputs(run, trial) {
  const lines = fs.readFileSync(`${TRIALS}/${run}/${trial}.transcript.jsonl`, 'utf8').split('\n').filter(Boolean)
  return JSON.stringify(lines.map((l) => { try { return JSON.parse(l) } catch { return null } }).filter((l) => l?.type === 'assistant')
    .flatMap((l) => (l.message.content ?? []).filter((b) => b.type === 'tool_use').map((b) => b.input))).replaceAll('references/', 'llms/')
}
say('## What the trials opened\n')
say('| Run | ' + Object.keys(OPENED).join(' | ') + ' | the task\'s matching file (14 of the 15 tasks have one) | failed build/test runs, mean |')
say('|---|' + Object.keys(OPENED).map(() => '---').join('|') + '|---|---|')
json.opened = {}
for (const [name, cfg] of Object.entries(RUNS)) {
  if (name === 'pilot') continue
  for (const arm of cfg.arms) {
    const run = cfg.run(arm), ts = load(run).map((t) => ({ ...t, inputs: toolInputs(run, t.a.trial) }))
    const shares = Object.values(OPENED).map((re) => ts.filter((t) => re.test(t.inputs)).length)
    const topical = ts.filter((t) => TRIGGER[t.task.slice(0, 2)]), matched = topical.filter((t) => TRIGGER[t.task.slice(0, 2)].test(t.inputs)).length
    const failed = mean(ts.map((t) => t.a.failures.filter((f) => f.kind === 'verify').length))
    json.opened[`${arm}-${name}`] = { trials: ts.length, opened: Object.fromEntries(Object.keys(OPENED).map((k, i) => [k, shares[i]])), matched, topical: topical.length, failedRuns: failed }
    say(`| ${arm}, ${name} | ${shares.map((n) => `${n}/${ts.length}`).join(' | ')} | ${matched}/${topical.length} (${pct(matched / topical.length)}) | ${failed.toFixed(1)} |`)
  }
}
say()
fs.writeFileSync(path.join(here, '../data/results.md'), out.join('\n'))
fs.writeFileSync(path.join(here, '../data/results.json'), JSON.stringify(json, null, 1) + '\n')
console.log(out.join('\n'))
