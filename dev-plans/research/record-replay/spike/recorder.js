// Record/replay spike: the recorder. A hook layer (src/core/hooks.ts) registered on the dev
// bridge (globalThis.__SYGNAL_DIAGNOSTICS__.layers), as sygnal/devtools' action log is: the
// core calls no recorder code and the main bundle doesn't grow (0 B). It records the first app
// started after startRecording() (run() or renderComponent()).
//
// What it captures (the log format, README §4):
//   init     the root state when the app started (after INITIALIZE)
//   sources  the app's source names that aren't built in: 'resources' (makeFetchDriver), 'timers'
//            (makeTimerDriver), else 'other' (the replay gives those an inert driver)
//   p        the instance addresses (./address.js); actions point into it
//   a        every action, in queue order: { s: seq, t: ms since the previous one, p, y: type,
//            c: cause code, r: a reply's source (driver name), d: data (inputs only, ./format.js encode), e: entropy the handlers
//            read, h: hash of the instance's new state (when its STATE changed), f: the hashes of
//            the values its other sinks produced, [sink, hash] }
//   k        checkpoints, one per patch (one per flush that changed the vnode): { s: the last
//            action before it, v: vnode hash, o: the root state's diff from the previous one }
//   fx       declaration statics sent to drivers (resources, timers, ...), [seq, sink, hash]
//   end      the final root state's diff from the last checkpoint, and the session's length
//
// Inputs (the replay dispatches them from the log): causes intent, reply, next, simulateAction,
// behavior, agent. Consequences (regenerated by the code under replay; recorded without data so
// the replay can compare them): built-in (INITIALIZE, BOOTSTRAP, DISPOSE) and parent.
import { encode, plain, diff, vnodeString, fnv, mask, maskAll, redactInput, stable, isTextEntry } from './format.js'
import { withEntropy, recordInto } from './entropy.js'
import { addresses } from './address.js'

export const CAUSE = { intent: 'i', reply: 'r', next: 'n', simulateAction: 'a', behavior: 'B', agent: 'g', 'built-in': 'b', parent: 'p', setState: 'S' }
export const INPUT = new Set(['i', 'r', 'n', 'a', 'B', 'g'])
const STANDARD = /^(DOM|EVENTS|STATE|LOG|CHILD|PARENT|READY|props\$|children\$|dispose\$|__.*)$/

/** the layer's clock (performance.now when there is one) */
const clock = () => (globalThis.performance ? performance.now() : Date.now())
const realNow = Date.now.bind(Date)

/**
 * Start recording the next app. Options:
 *   redact     true, or { keep: [types], also: [types] }: by provenance, the strings of
 *              - intent actions dispatched while a text-entry DOM event (./format.js isTextEntry)
 *                is being delivered (the DOM sources are wrapped: wrapSources), and of every
 *                later action of a type that was once dispatched that way;
 *              - reply actions (server data);
 *              - the types in `also`; never those in `keep`, nor next() data (the code's own)
 *              are pseudonymized (./format.js pseudo: same shape, equality kept), and every
 *              checkpoint is stored and compared on masked values (maskAll), so no typed or
 *              server text is stored. A redacted string the model branches on (a route name)
 *              makes the replay diverge at that action: add it to `keep` (README §7)
 *   dropNoops  (default true) leave out input actions that changed nothing: no state change, no
 *              sink value, no EFFECT, no entropy (an idle timer's ticks, a click with no model
 *              entry). A replay of the same code is unaffected; see README §6 for the trade-off
 *   vnodes     'hash' (default) or 'html' (each checkpoint also keeps the markup, for reports)
 *   profile    an object: filled with the ms spent in each hook (the README §8 breakdown)
 * Returns { stop(): the log, log(): the log so far, active() }
 */
export function startRecording({ redact = false, dropNoops = true, vnodes = 'hash', profile = null } = {}) {
  const D = (globalThis.__SYGNAL_DIAGNOSTICS__ ||= {})
  const L = (D.layers ||= new Set())
  let log = null
  let stopped = false
  let api = null
  const keep = new Set((redact && redact.keep) || [])
  const textTypes = new Set((redact && redact.also) || [])
  const salt = Math.random().toString(36).slice(2)
  let typing = 0      // > 0 while a text-entry DOM event is being delivered
  const norm = redact ? v => maskAll(plain(v)) : plain
  const h = v => fnv(stable(norm(v)))
  const text = redact ? mask : undefined

  const factory = a => {
    if (log || stopped) return {}
    api = a
    const addr = addresses()
    const paths = new Map()
    const pathIdx = p => {
      let i = paths.get(p)
      if (i === undefined) { i = log.p.length; paths.set(p, i); log.p.push(p) }
      return i
    }
    let seq = 0
    let last = clock()
    const t0 = last
    let cur = null       // the action whose handlers run now
    let prevState        // the root state at the last checkpoint (normalized)
    let marks = 0        // log.a entries a noop may be dropped from

    log = { v: 1, kind: 'sygnal-recording', app: undefined, recorded: new Date(realNow()).toISOString(), redacted: !!redact, sources: {}, init: undefined, p: [], a: [], k: [], fx: [] }

    let prevLast = last
    const finishCur = () => {
      if (!cur) return
      const x = cur
      cur = null
      if (dropNoops && INPUT.has(x.c) && !x.h && !x.f && !x.e && !x.x && log.a[log.a.length - 1] === x) {
        log.a.pop()
        marks++
        last = prevLast   // the next entry's `t` counts from the last one kept
      }
      delete x.x
    }

    const hooks = {
      onCreate(iv) {
        const a = addr.create(iv)
        if (iv.isRoot && log.app === undefined) {
          log.app = iv.name
          // (unmasked even when redacting: it is the code's initialState or run()'s, README §7)
          log.init = plain(api.getState())
          for (const [n, s] of Object.entries(iv.sources || {})) {
            if (STANDARD.test(n)) continue
            log.sources[n] = s && s.__sygnalStatic === 'resources' ? 'resources' : s && s.__sygnalStatic === 'timers' ? 'timers' : 'other'
          }
          prevState = norm(log.init)
        }
        pathIdx(a)
      },
      onDispose(iv) { addr.dispose(iv) },
      wrapSources: redact ? (iv, sources) => {
        if (!sources.DOM) return sources
        return { ...sources, DOM: tapDOM(sources.DOM, e => isTextEntry(e), on => { typing += on ? 1 : -1 }) }
      } : undefined,
      onAction(iv, action) {
        if (stopped) return
        finishCur()
        const now = clock()
        const c = CAUSE[action.cause] || action.cause
        const entry = { s: ++seq, t: Math.round(now - last), p: pathIdx(addr.of(iv)), y: action.type, c }
        if (c == 'r' && action.source) entry.r = action.source
        prevLast = last
        last = now
        if (INPUT.has(c) && action.data !== undefined) {
          // an intent over the instance's own STATE stream: replayed with its current state (README §4)
          if (c == 'i' && isEcho(action.data, iv.state)) entry.d = { $echo: 1 }
          else {
            let d = encode(action.data)
            if (redact && c == 'i' && typing > 0) textTypes.add(action.type)
            if (redact && !keep.has(action.type) && (c == 'r' || (c == 'i' && textTypes.has(action.type)))) d = redactInput(d, salt)
            entry.d = d
          }
        }
        log.a.push(entry)
        cur = entry
      },
      wrapHandler(iv, type, sink, fn) {
        if (stopped || typeof fn != 'function') return fn
        const entry = cur
        return (...args) => {
          if (!entry) return fn(...args)
          if (sink == 'EFFECT') entry.x = 1
          const got = []
          try { return withEntropy(recordInto(got), () => fn(...args)) } finally {
            if (got.length) (entry.e ||= []).push(...got)
          }
        }
      },
      onReducer(iv, type, prev, next) {
        if (stopped || !cur) return
        cur.h = h(next)
      },
      onSink(iv, type, sink, value) {
        if (stopped) return
        if (type === null) { log.fx.push([seq, sink, h(value)]); return }
        if (cur) (cur.f ||= []).push([sink, h(value)])
      },
      onPatch(vnode) {
        if (stopped) return
        finishCur()
        const s = norm(api.getState())
        const cp = { s: seq, v: fnv(vnodeString(vnode, text)) }
        const o = diff(prevState, s)
        if (o.length) cp.o = o
        if (vnodes == 'html') cp.html = vnodeString(vnode, text)
        prevState = s
        log.k.push(cp)
      },
    }
    if (profile) for (const k of Object.keys(hooks)) {
      const f = hooks[k]
      if (typeof f != 'function') continue
      hooks[k] = function (...args) {
        const t = performance.now()
        try { return f.apply(this, args) } finally { profile[k] = (profile[k] || 0) + performance.now() - t }
      }
    }
    finish = () => {
      finishCur()
      const s = norm(api.getState())
      const o = diff(prevState, s)
      log.end = { s: seq, ms: Math.round(clock() - t0), dropped: marks, ...(o.length ? { o } : {}) }
    }
    return hooks
  }
  let finish
  L.add(factory)
  return {
    log: () => log,
    active: () => !!log && !stopped,
    stop() {
      L.delete(factory)
      if (log && !stopped) finish()
      stopped = true
      return log
    },
  }
}

/** the data is the instance's own state (an intent over STATE.stream; calculated fields may be added) */
function isEcho(data, state) {
  if (!data || !state || typeof data != 'object' || typeof state != 'object' || Array.isArray(data)) return false
  if (data === state) return true
  const keys = Object.keys(state)
  return keys.length > 0 && keys.every(k => data[k] === state[k])
}

const isStream = x => !!x && typeof x.addListener == 'function' && typeof x._n == 'function'

/**
 * The DOM source with every event stream tapped: while an event that `test` accepts is being
 * delivered (synchronously, through the intent's operators to dispatch), `mark(true)` /
 * `mark(false)` bracket it. The stream object is patched in place (its `_n`), so the helpers
 * sygnal adds to it (.value(), .data()) keep working.
 */
function tapDOM(src, test, mark) {
  const tap = s => {
    if (!isStream(s) || s.__rrTapped) return s
    const n = s._n
    s._n = function (e) {
      const on = test(e)
      if (on) mark(true)
      try { return n.call(this, e) } finally { if (on) mark(false) }
    }
    Object.defineProperty(s, '__rrTapped', { value: true })
    return s
  }
  const wrap = o => new Proxy(o, {
    get(t, k) {
      const v = Reflect.get(t, k, t)
      if (typeof v != 'function' || typeof k == 'symbol' || k.startsWith('isolate') || k.startsWith('__')) return v
      return (...args) => {
        const r = v.apply(t, args)
        return isStream(r) ? tap(r) : r && typeof r == 'object' && typeof r.events == 'function' ? wrap(r) : r
      }
    },
  })
  return wrap(src)
}
