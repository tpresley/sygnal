#!/usr/bin/env node
// Files touched before and after each fix: reference solutions (real rewrites from rewrite.mjs) and trials.
//
//   node dev-plans/research/files-touched/rewrite.mjs <out>
//   node dev-plans/research/files-touched/scenarios.mjs <out>
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { lineDiff } from '../../../evals/agent-ergonomics/analysis/lib/code.mjs'
import { isTestPath } from '../../../evals/agent-ergonomics/analysis/lib/classify.mjs'
import { loadRuns, MAINLINE, ratioStats } from './diff-size.mjs'
import { referencePairs, trialPairs, causeOf } from './classify.mjs'
import { F1_TASKS, F2_TASKS } from './rewrite.mjs'

const out = path.resolve(process.argv[2] ?? 'out')
const isSrc = (f) => /^src\/.*\.(jsx?|tsx?|mjs|cjs|css)$/.test(f) && !isTestPath(f) && !/(^|\/)(test-utils|fixtures|setupTests)[^/]*$/.test(f)

function treeFiles(dir) {
  const o = {}
  const w = (d, rel) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const r = path.posix.join(rel, e.name)
      if (e.isDirectory()) w(path.join(d, e.name), r)
      else o[r] = fs.readFileSync(path.join(d, e.name), 'utf8')
    }
  }
  w(dir, '')
  return o
}
/** One rewritten task: source files that differ between its starter and solution trees. */
function rewritten(fix, task) {
  const s = treeFiles(path.join(out, fix, task, 'starter'))
  const d = treeFiles(path.join(out, fix, task, 'solution'))
  const files = {}
  for (const f of new Set([...Object.keys(s), ...Object.keys(d)])) {
    if (!isSrc(f) || s[f] === d[f]) continue
    files[f] = { p: 1, status: s[f] == null ? 'new' : d[f] == null ? 'deleted' : 'modified' }
  }
  return files
}

const refs = referencePairs()
const sum = (o) => Object.values(o).reduce((a, x) => a + x.p, 0)
const withFix = (pairs, f) => pairs.map((p) => ({ ...p, sygnal: f(p.task, p.sygnal) ?? p.sygnal }))
const drop = (files, keep) => Object.fromEntries(Object.entries(files).filter(([k, v]) => keep(k, v)))

const F1 = (t) => (F1_TASKS.includes(t) ? rewritten('root-drivers', t) : null)
const F2 = (t) => (F2_TASKS.includes(t) ? rewritten('ts-colocate', t) : null)
const noEntry = (ts) => (t, s) => (ts.includes(t) ? drop(s, (f) => causeOf(f, s[f].status) !== 'entry') : s)
// the fixes compose on the Sygnal arm's file set (F1 rewrites only JS tasks, F2 only TS tasks)
const compose = (...fs) => (t, s) => fs.reduce((acc, f) => f(t, acc) ?? acc, s)
// A: a plugin / run() default supplies a driver only where every driver is built in and takes no options
const AUTO_REF = ['23-quote-resource', '26-autosave-draft', '30-checkout-form']
const AUTO_REF_ALL = [...AUTO_REF, '05-driver-quote', '11-search-debounce', '13-course-portal', '17-address-lookup', '22-chat-socket']
// trials: hand-written driver files are rare there, so tasks whose natural solution is a zero-option built-in
const AUTO_TRIAL = [...AUTO_REF_ALL, '28-stopwatch']
const noDriverFile = (t, s) => (['05-driver-quote', '11-search-debounce', '22-chat-socket', '26-autosave-draft'].includes(t) ? drop(s, (f) => !/quoteDriver|searchDriver|chatSocket|draft\.js/.test(f)) : s)
const noRoutes = (t, s) => (['25-router-spa', '43-expenses-remove-settings'].includes(t) ? drop(s, (f) => causeOf(f, s[f].status) !== 'routes') : s)

const f2 = (x) => x.toFixed(2)
const stat = (pairs) => {
  const s = pairs.map((p) => sum(p.sygnal))
  const r = pairs.map((p) => sum(p.react))
  const mean = (xs) => xs.reduce((a, x) => a + x, 0) / xs.length
  const st = ratioStats(pairs.map((p) => [Math.max(sum(p.sygnal), 0.5), sum(p.react)]))
  return { s: mean(s), r: mean(r), gap: mean(s) - mean(r), ratio: st.ratio, lo: st.lo, hi: st.hi }
}
const row = (label, pairs, base) => {
  const x = stat(pairs)
  const closed = base ? `${(((base.ratio - x.ratio) / (base.ratio - 1)) * 100).toFixed(0)}%` : ''
  return `| ${label} | ${f2(x.s)} | ${f2(x.r)} | ${f2(x.ratio)}× [${f2(x.lo)}, ${f2(x.hi)}] | ${closed} |`
}
const HEADER = ['| Scenario | Sygnal | React | S/R (95% CI) | Gap closed |', '|---|---|---|---|---|']

const lines = ['# Files touched: before and after each fix', '', 'Generated by `scenarios.mjs`. Reference solutions marked "rewritten" are real files built by `rewrite.mjs`; the others are computed by removing a file from the Sygnal set. Gap closed: share of (ratio − 1) removed.', '', '## Reference solutions', '', ...HEADER]
const base = stat(refs)
lines.push(row('Today', refs))
lines.push(row('A. Auto-supply zero-option built-ins (Vite plugin or `run()` default), as the references are written (23, 26, 30)', withFix(refs, noEntry(AUTO_REF)), base))
lines.push(row('A+. The same, if the 5 custom-driver references also used built-ins (+05, 11, 13, 17, 22)', withFix(refs, noEntry(AUTO_REF_ALL)), base))
lines.push(row('F1. `App.drivers` (rewritten, 13 tasks)', withFix(refs, F1), base))
lines.push(row('F2. TypeScript types next to the code (rewritten, 4 tasks)', withFix(refs, F2), base))
lines.push(row('F1 + F2', withFix(refs, compose(F1, F2)), base))
lines.push(row('F1 + F2 + no hand-written driver / draft files (estimate: references updated to built-ins, as trials already do)', withFix(refs, compose(F1, F2, noDriverFile)), base))
lines.push(row('F1 + F2 + driver files + no routes file (25, 43)', withFix(refs, compose(F1, F2, noDriverFile, noRoutes)), base))

// Trials: per trial, so "App.* touched too" is exact; an entry edit moves into App.* (one file fewer) only if App.* is touched.
const fam = (m) => (m ? m.replace(/^claude-/, '').replace(/-\d{8}$/, '') : 'unknown')
const runs = loadRuns()
const isEntry = (f) => causeOf(f, 'modified') === 'entry'
const isAppFile = (f) => /^src\/App\.[jt]sx?$/.test(f)
function trials(transform) {
  const cells = {}
  for (const arm of ['sygnal', 'react']) {
    for (const run of MAINLINE[arm]) {
      const groups = {}
      for (const t of runs[run] ?? []) {
        if (t.arm !== arm || !t.diff || !t.scored?.pass) continue
        ;(groups[`${fam(t.usage?.model ?? t.model)}|${t.task}`] ??= []).push(t)
      }
      for (const [k, ts] of Object.entries(groups)) {
        const c = (cells[k] ??= {})
        if (c[arm]) continue
        const p = {}
        for (const t of ts) {
          let files = Object.fromEntries(Object.entries(t.diff.files ?? {}).filter(([f]) => isSrc(f)))
          if (arm === 'sygnal' && transform) files = transform(k.split('|')[1], files)
          for (const [f, d] of Object.entries(files)) {
            p[f] ??= { p: 0, status: d.status }
            p[f].p += 1 / ts.length
          }
        }
        c[arm] = p
      }
    }
  }
  return Object.entries(cells).filter(([, c]) => c.sygnal && c.react).map(([k, c]) => ({ model: k.split('|')[0], task: k.split('|')[1], sygnal: c.sygnal, react: c.react }))
}
const NOT_MOVED = ['47-board-agent-tools']
const tF1 = (task, files) => (NOT_MOVED.includes(task) ? files : Object.keys(files).some(isAppFile) ? drop(files, (f) => !isEntry(f)) : files)
const tF2 = (task, files) => (F2_TASKS.includes(task) ? drop(files, (f) => causeOf(f, files[f].status) !== 'types') : files)
const tA = (task, files) => (AUTO_TRIAL.includes(task) ? drop(files, (f) => !isEntry(f)) : files)

lines.push('', '## Trials (passing, newest mainline run per cell)', '')
for (const m of ['opus-5-5', 'sonnet-5-5', 'haiku-4-5', 'all']) {
  const pick = (ps) => (m === 'all' ? ps : ps.filter((p) => p.model === m))
  const b = pick(trials(null))
  const baseT = stat(b)
  lines.push(`### ${m} (${b.length} tasks)`, '', ...HEADER)
  lines.push(row('Today', b))
  lines.push(row('A. Auto-supply zero-option built-ins (upper bound: main.js dropped in 05, 11, 13, 17, 22, 23, 26, 28, 30)', pick(trials(tA)), baseT))
  lines.push(row('F1. `App.drivers`', pick(trials(tF1)), baseT))
  lines.push(row('F2. Types next to the code', pick(trials(tF2)), baseT))
  lines.push(row('F1 + F2', pick(trials((t, f) => tF2(t, tF1(t, f)))), baseT), '')
}

// how often an entry edit comes with an App.* edit (the F1 saving needs both)
let withApp = 0, entryT = 0
for (const run of MAINLINE.sygnal) for (const t of runs[run] ?? []) {
  if (t.arm !== 'sygnal' || !t.diff || !t.scored?.pass) continue
  const files = Object.keys(t.diff.files ?? {}).filter(isSrc)
  if (files.some(isEntry)) { entryT++; if (files.some(isAppFile)) withApp++ }
}
lines.push(`Trials that edit the entry point: ${entryT}; of those, ${withApp} (${((100 * withApp) / entryT).toFixed(0)}%) also edit \`App.*\`.`, '')

// per-task entry rate over models
const perTask = {}
for (const p of trials(null)) (perTask[p.task] ??= []).push(Object.entries(p.sygnal).filter(([f]) => isEntry(f)).reduce((a, [, x]) => a + x.p, 0))
lines.push('Entry-file touch rate by task, Sygnal arm (mean over models):', '', '| Task | rate |', '|---|---|')
for (const [t, v] of Object.entries(perTask).sort()) { const mean = v.reduce((a, b) => a + b, 0) / v.length; if (mean > 0) lines.push(`| ${t} | ${f2(mean)} |`) }
const here = path.dirname(fileURLToPath(import.meta.url))
fs.writeFileSync(path.join(here, 'scenarios-table.md'), lines.join('\n') + '\n')
console.log(lines.join('\n'))
